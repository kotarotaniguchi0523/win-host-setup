# capture.ps1 - real environment -> repository (source)
# Usage: pwsh -File tools/capture.ps1
#  - ~/.config/mise/config.toml → mise/mise.toml
#  - ~/.config/mise/mise.lock   → mise/mise.lock
#  - ~/.config/mise/locks/      → mise/locks/
#  - user environment variables -> env/variables.md (**secrets are masked**)

[CmdletBinding()]
param([switch]$Force)
$ErrorActionPreference = 'Stop'
# Run standalone too: the shared helpers (Get-HomeDir etc.) live in lib/common.ps1
. (Join-Path $PSScriptRoot 'lib\common.ps1')
$repo    = Split-Path $PSScriptRoot -Parent
$miseSrc = Join-Path $env:USERPROFILE '.config\mise'
$miseDst = Join-Path $repo 'mise'

if (-not (Test-Path $miseSrc)) { throw "見つかりません: $miseSrc" }
New-Item -ItemType Directory -Force -Path $miseDst | Out-Null

# Save config.toml under the name mise.toml so mise does not pick it up inside the repository
if (-not $Force -and (Test-Path "$miseDst\mise.toml") -and ((Get-FileHash "$miseSrc\config.toml").Hash -ne (Get-FileHash "$miseDst\mise.toml").Hash)) {
    Write-Warning 'mise/mise.toml がホストと不一致: スキップ（-Force でホスト優先 / tools/pull.ps1 でリポジトリ優先）'
} else {
    Copy-Item (Join-Path $miseSrc 'config.toml') (Join-Path $miseDst 'mise.toml') -Force
    Write-Host '[ok] mise/mise.toml'
}
Copy-Item (Join-Path $miseSrc 'mise.lock')   (Join-Path $miseDst 'mise.lock') -Force
Write-Host "[ok] mise/mise.lock"

$locks = Join-Path $miseSrc 'locks'
if (Test-Path $locks) {
    $dst = Join-Path $miseDst 'locks'
    if (Test-Path $dst) { Remove-Item $dst -Recurse -Force }
    Copy-Item $locks $dst -Recurse -Force
    Write-Host "[ok] mise/locks （$((Get-ChildItem $dst -Recurse -File).Count) ファイル）"
}

# Environment variables (User scope) - do not save secrets
$secret = @('CONTEXT7_API_KEY', 'GH_TOKEN', 'GITHUB_TOKEN', 'OPENAI_API_KEY', 'ANTHROPIC_API_KEY', 'TAKUMI_TOKEN', 'RENOVATE_TOKEN')
$envDir = Join-Path $repo 'env'
New-Item -ItemType Directory -Force -Path $envDir | Out-Null
# Apply the same PII rules as depii/sanitize, so a capture alone never writes real paths into the
# source (the values come from the live environment).
. (Join-Path $repo 'tools\pii-rules.ps1')
$piiRules = Get-PiiRules -Repo $repo
$lines = @('# ユーザー環境変数（User スコープ・キャプチャ）', '', '| 変数 | 値 |', '|---|---|')
foreach ($name in ([Environment]::GetEnvironmentVariables('User').Keys | Sort-Object)) {
    $val = [Environment]::GetEnvironmentVariable($name, 'User')
    $shown = if ($secret -contains $name) { '<secret: リポジトリに保存しない>' } else { $val }
    foreach ($k in $piiRules.Keys) { if ($k) { $shown = $shown.Replace($k, $piiRules[$k]) } }
    $lines += ('| `' + $name + '` | `' + $shown + '` |')
}
$lines += @('', '> 生成: `tools/capture.ps1`。秘密値は保存していない。')
$lines | Set-Content (Join-Path $envDir 'variables.md') -Encoding UTF8
Write-Host "[ok] env/variables.md"

# --- shell config (Nushell): ~/.config/nushell -> shell/nushell ---
$shellSrc = Join-Path (Get-HomeDir) '.config/nushell'
$shellDst = Join-Path $repo 'shell/nushell'
if (Test-Path $shellSrc) {
    New-Item -ItemType Directory -Force -Path $shellDst | Out-Null
    foreach ($f in 'config.nu', 'env.nu') {
        $p = Join-Path $shellSrc $f
        if (Test-Path $p) { Copy-Item $p (Join-Path $shellDst $f) -Force; Write-Host "[ok] shell/nushell/$f" }
    }
    $autoSrc = Join-Path $shellSrc 'autoload'
    if (Test-Path $autoSrc) {
        $autoDst = Join-Path $shellDst 'autoload'
        New-Item -ItemType Directory -Force -Path $autoDst | Out-Null
        Get-ChildItem $autoSrc -File | Where-Object { $_.Name -ne 'mise.nu' } | ForEach-Object {  # mise.nu is regenerated by apply
            Copy-Item $_.FullName (Join-Path $autoDst $_.Name) -Force
            Write-Host "[ok] shell/nushell/autoload/$($_.Name)"
        }
    }
} else {
    Write-Host "[i] $shellSrc がありません（Nushell 未設定）"
}
